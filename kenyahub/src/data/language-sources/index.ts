export function normalizeLanguageId(languageId: string): string {
  const withoutParens = languageId.split('(')[0] ?? languageId;
  const normalized = withoutParens
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
  return LANGUAGE_ID_ALIASES[normalized] ?? normalized;
}

// ── Pre-Indexed O(1) Source Lookups ──

const SOURCES_BY_ID_MAP = new Map<string, LanguageSource>(
  LANGUAGE_SOURCES.map((source) => [source.id, source])
);

const SOURCES_BY_LANGUAGE_MAP: Map<string, LanguageSource[]> = (() => {
  const map = new Map<string, LanguageSource[]>();
  for (const source of LANGUAGE_SOURCES) {
    for (const langId of source.languages) {
      let bucket = map.get(langId);
      if (!bucket) {
        bucket = [];
        map.set(langId, bucket);
      }
      bucket.push(source);
    }
  }
  return map;
})();

export function getSourcesForLanguage(languageId: string): LanguageSource[] {
  const normalizedId = normalizeLanguageId(languageId);
  return SOURCES_BY_LANGUAGE_MAP.get(normalizedId) ?? [];
}

export function getSourceById(sourceId: string): LanguageSource | undefined {
  return SOURCES_BY_ID_MAP.get(sourceId);
}

