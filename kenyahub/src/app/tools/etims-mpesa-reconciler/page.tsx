"use client";

import { useState, useMemo } from "react";
import { ShieldAlert, CheckCircle2, Download, MessageSquare, Plus, Trash2 } from "lucide-react";
import ToolShell from "@/components/tools/ToolShell";
import CustomSelect from "@/components/ui/CustomSelect";
import { TOOLS } from "@/lib/tools-registry";
import utilData from "@/data/kenya-utility-tools-2026.json";

const tool = TOOLS.find((t) => t.slug === "etims-mpesa-reconciler")!;

interface MpesaRow {
  id: string;
  date: string;
  ref: string;
  counterparty: string;
  phone: string;
  amount: number;
  category: string;
  exempt: boolean;
  matchedInvoice?: string;
}

const EXEMPT_CATEGORIES = new Set(["Emoluments", "Imports", "Airline Tickets", "Investment Allowances", "Interest / Bank Fees"]);

export default function EtimsMpesaReconcilerPage() {
  const [rows, setRows] = useState<MpesaRow[]>(() =>
    utilData.etims.sampleMpesaRows.map((r, i) => ({
      ...r,
      id: `m-${i}`,
      exempt: EXEMPT_CATEGORIES.has(r.category),
      matchedInvoice: utilData.etims.sampleEtimsRows.find(
        (e) => Math.abs(e.amount - r.amount) <= 10 && e.date === r.date
      )?.cuInvoice,
    }))
  );
  const [newCounterparty, setNewCounterparty] = useState("");
  const [newPhone, setNewPhone] = useState("");
  const [newAmount, setNewAmount] = useState("");
  const [newCategory, setNewCategory] = useState("Supplies");
  const [copiedMsg, setCopiedMsg] = useState<string | null>(null);

  const summary = useMemo(() => {
    let totalSpend = 0;
    let matchedSpend = 0;
    let exemptSpend = 0;
    let unreceiptedSpend = 0;
    for (const r of rows) {
      totalSpend += r.amount;
      if (r.matchedInvoice) matchedSpend += r.amount;
      else if (r.exempt) exemptSpend += r.amount;
      else unreceiptedSpend += r.amount;
    }
    const taxPenaltyExposure = Math.round(unreceiptedSpend * utilData.etims.corporateTaxPenaltyRate);
    return { totalSpend, matchedSpend, exemptSpend, unreceiptedSpend, taxPenaltyExposure };
  }, [rows]);

  const addRow = () => {
    const amt = Number(newAmount.replace(/,/g, ""));
    if (!newCounterparty.trim() || !amt || amt <= 0) return;
    const today = new Date().toISOString().slice(0, 10);
    setRows((prev) => [
      {
        id: `m-${Date.now()}`,
        date: today,
        ref: `MP${Math.floor(100000 + Math.random() * 900000)}`,
        counterparty: newCounterparty.trim(),
        phone: newPhone.trim() || "0700000000",
        amount: amt,
        category: newCategory,
        exempt: EXEMPT_CATEGORIES.has(newCategory),
      },
      ...prev,
    ]);
    setNewCounterparty("");
    setNewPhone("");
    setNewAmount("");
  };

  const toggleMatched = (id: string) => {
    setRows((prev) =>
      prev.map((r) =>
        r.id === id
          ? { ...r, matchedInvoice: r.matchedInvoice ? undefined : `KRA012026${Math.floor(100000 + Math.random() * 899999)}` }
          : r
      )
    );
  };

  const toggleExempt = (id: string) => {
    setRows((prev) => prev.map((r) => (r.id === id ? { ...r, exempt: !r.exempt } : r)));
  };

  const removeRow = (id: string) => {
    setRows((prev) => prev.filter((r) => r.id !== id));
  };

  const exportReverseInvoiceCsv = () => {
    const unmatched = rows.filter((r) => !r.matchedInvoice && !r.exempt);
    const disclaimerRow =
      '"UNOFFICIAL WORKING DRAFT — Generated by KenyaHub (independent tool, not affiliated with KRA). Verify and submit exclusively via the official KRA eTIMS portal."';
    const header = "TransactionDate,MpesaRef,SupplierName,SupplierPhone,AmountKES,Category,DraftClassification";
    const lines = unmatched.map(
      (r) => `${r.date},${r.ref},"${r.counterparty.replace(/"/g, '""')}",${r.phone},${r.amount},"${r.category}",Unofficial-Draft-Buyer-Initiated-eTIMS`
    );
    const blob = new Blob([[disclaimerRow, header, ...lines].join("\n")], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "kenyahub-etims-reconciliation-draft.csv";
    a.click();
    URL.revokeObjectURL(url);
  };

  const copyWhatsappChase = (r: MpesaRow) => {
    const msg = `Hello ${r.counterparty}, kindly share the KRA eTIMS Tax Invoice (CU Invoice No.) for our M-Pesa payment of KES ${r.amount.toLocaleString()} (Ref: ${r.ref}, Date: ${r.date}) for our 2026 KRA compliance records. Thank you.`;
    navigator.clipboard?.writeText(msg);
    setCopiedMsg(r.id);
    setTimeout(() => setCopiedMsg(null), 2000);
  };

  return (
    <ToolShell tool={tool}>
      <div className="space-y-6">
        <div className="rounded-2xl border border-gold/30 bg-bg-card p-5 sm:p-7 shadow-xs">
          <div className="flex flex-wrap items-center justify-between gap-3 mb-3">
            <h2 className="text-lg font-bold font-[family-name:var(--font-outfit)] text-text-primary flex items-center gap-2">
              <ShieldAlert className="w-5 h-5 text-gold" />
              Local-First eTIMS &amp; M-Pesa Disallowed-Expense Shield
            </h2>
            <span className="text-xs px-2.5 py-1 rounded-full bg-emerald-500/15 text-emerald-400 border border-emerald-500/30 font-semibold">
              100% Client-Side • Zero Cloud Upload
            </span>
          </div>
          <p className="text-xs sm:text-sm text-text-secondary leading-relaxed mb-6">
            Under KRA&apos;s 2026 automated eTIMS cross-matching rules, every unreceipted business expense is disallowed for corporate tax, creating a <strong>30% tax penalty</strong> (KES 300,000 per KES 1,000,000 unreceipted spend). Reconcile M-Pesa Paybill/Till outflows, tag statutory exemptions, and export unofficial working-draft CSVs locally for your accountant or manual entry on the official KRA eTIMS portal.
          </p>

          {/* Live Tax Exposure Ticker */}
          <div className="grid grid-cols-1 sm:grid-cols-4 gap-3 mb-6">
            <div className="rounded-xl border border-red-500/40 bg-red-500/10 p-4">
              <span className="text-[0.6875rem] font-bold text-red-400 uppercase">30% KRA Tax Exposure</span>
              <p className="text-2xl font-black text-red-400 mt-1">
                KES {summary.taxPenaltyExposure.toLocaleString()}
              </p>
              <p className="text-[0.6875rem] text-text-secondary mt-1">
                On KES {summary.unreceiptedSpend.toLocaleString()} unreceipted
              </p>
            </div>
            <div className="rounded-xl border border-emerald-500/35 bg-emerald-500/10 p-4">
              <span className="text-[0.6875rem] font-bold text-emerald-400 uppercase">eTIMS Matched</span>
              <p className="text-xl font-bold text-text-primary mt-1">
                KES {summary.matchedSpend.toLocaleString()}
              </p>
              <p className="text-[0.6875rem] text-text-muted mt-1">Validated CU Invoice</p>
            </div>
            <div className="rounded-xl border border-sky-500/35 bg-sky-500/10 p-4">
              <span className="text-[0.6875rem] font-bold text-sky-400 uppercase">Statutory Exempt</span>
              <p className="text-xl font-bold text-text-primary mt-1">
                KES {summary.exemptSpend.toLocaleString()}
              </p>
              <p className="text-[0.6875rem] text-text-muted mt-1">Payroll, imports, airfare</p>
            </div>
            <div className="rounded-xl border border-border bg-bg-elevated/40 p-4">
              <span className="text-[0.6875rem] font-bold text-text-muted uppercase">Total Audited Spend</span>
              <p className="text-xl font-bold text-text-primary mt-1">
                KES {summary.totalSpend.toLocaleString()}
              </p>
              <p className="text-[0.6875rem] text-text-muted mt-1">{rows.length} M-Pesa ledger lines</p>
            </div>
          </div>

          {/* Add Expense Line */}
          <div className="grid grid-cols-1 sm:grid-cols-5 gap-2.5 mb-5 p-3.5 rounded-xl bg-bg-elevated/60 border border-border">
            <input
              type="text"
              value={newCounterparty}
              onChange={(e) => setNewCounterparty(e.target.value)}
              placeholder="Supplier / Paybill name"
              className="sm:col-span-2 px-3 py-2 rounded-lg border border-border bg-bg-card text-xs text-text-primary outline-hidden focus:border-gold"
            />
            <input
              type="text"
              value={newAmount}
              onChange={(e) => setNewAmount(e.target.value.replace(/[^0-9]/g, ""))}
              placeholder="Amount (KES)"
              className="px-3 py-2 rounded-lg border border-border bg-bg-card text-xs text-text-primary outline-hidden focus:border-gold"
            />
            <CustomSelect
              value={newCategory}
              onChange={(e) => setNewCategory(e.target.value)}
              className="input-field w-full text-xs"
            >
              <option value="Supplies">Supplies (eTIMS Required)</option>
              <option value="Logistics">Logistics (eTIMS Required)</option>
              <option value="Services">Services (eTIMS Required)</option>
              <option value="Emoluments">Emoluments (Exempt)</option>
              <option value="Imports">Imports / iCMS (Exempt)</option>
              <option value="Airline Tickets">Airline Tickets (Exempt)</option>
              <option value="Interest / Bank Fees">Interest / Bank Fees (Exempt)</option>
            </CustomSelect>
            <button
              type="button"
              onClick={addRow}
              className="inline-flex items-center justify-center gap-1.5 px-3 py-2 rounded-lg bg-gold text-kenya-black text-xs font-bold hover:opacity-90 cursor-pointer"
            >
              <Plus className="w-3.5 h-3.5" /> Add Line
            </button>
          </div>

          {/* Ledger Table */}
          <div className="overflow-x-auto rounded-xl border border-border">
            <table className="w-full text-left text-xs">
              <thead className="bg-bg-elevated text-text-muted uppercase text-[0.65rem]">
                <tr>
                  <th className="px-3 py-2.5">Date / Ref</th>
                  <th className="px-3 py-2.5">Counterparty</th>
                  <th className="px-3 py-2.5">Amount (KES)</th>
                  <th className="px-3 py-2.5">Status</th>
                  <th className="px-3 py-2.5 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border">
                {rows.map((r) => (
                  <tr key={r.id} className="hover:bg-bg-elevated/30">
                    <td className="px-3 py-2.5 font-mono text-[0.7rem] text-text-muted">
                      <div>{r.date}</div>
                      <div>{r.ref}</div>
                    </td>
                    <td className="px-3 py-2.5">
                      <div className="font-semibold text-text-primary">{r.counterparty}</div>
                      <div className="text-[0.68rem] text-text-muted">{r.category} • {r.phone}</div>
                    </td>
                    <td className="px-3 py-2.5 font-bold text-text-primary">
                      KES {r.amount.toLocaleString()}
                    </td>
                    <td className="px-3 py-2.5">
                      {r.matchedInvoice ? (
                        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-emerald-500/15 text-emerald-400 font-semibold text-[0.68rem]">
                          <CheckCircle2 className="w-3 h-3" /> Matched ({r.matchedInvoice})
                        </span>
                      ) : r.exempt ? (
                        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-sky-500/15 text-sky-400 font-semibold text-[0.68rem]">
                          Statutory Exempt
                        </span>
                      ) : (
                        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-red-500/15 text-red-400 font-semibold text-[0.68rem]">
                          +KES {Math.round(r.amount * 0.3).toLocaleString()} Risk
                        </span>
                      )}
                    </td>
                    <td className="px-3 py-2.5 text-right">
                      <div className="inline-flex items-center gap-1.5">
                        <button
                          type="button"
                          onClick={() => toggleMatched(r.id)}
                          className="px-2 py-1 rounded-md border border-border bg-bg-elevated text-[0.68rem] text-text-secondary hover:text-gold cursor-pointer"
                        >
                          {r.matchedInvoice ? "Unmatch" : "Mark eTIMS"}
                        </button>
                        {!r.matchedInvoice && (
                          <button
                            type="button"
                            onClick={() => toggleExempt(r.id)}
                            className="px-2 py-1 rounded-md border border-border bg-bg-elevated text-[0.68rem] text-text-secondary hover:text-sky-400 cursor-pointer"
                          >
                            {r.exempt ? "Unexempt" : "Exempt"}
                          </button>
                        )}
                        {!r.matchedInvoice && !r.exempt && (
                          <button
                            type="button"
                            onClick={() => copyWhatsappChase(r)}
                            className="inline-flex items-center gap-1 px-2 py-1 rounded-md border border-emerald-500/40 bg-emerald-500/10 text-[0.68rem] text-emerald-400 cursor-pointer"
                          >
                            <MessageSquare className="w-3 h-3" />
                            {copiedMsg === r.id ? "Copied" : "Chase"}
                          </button>
                        )}
                        <button
                          type="button"
                          onClick={() => removeRow(r.id)}
                          className="p-1 text-text-muted hover:text-red-400 cursor-pointer"
                          aria-label="Remove row"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className="mt-4 flex flex-wrap items-center justify-between gap-3">
            <p className="text-[0.72rem] text-text-muted">
              Statutory exemptions per KRA eTIMS Guidelines: {utilData.etims.statutoryExemptions.join(" • ")}.
            </p>
            <button
              type="button"
              onClick={exportReverseInvoiceCsv}
              className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-gold text-kenya-black text-xs font-bold hover:opacity-90 cursor-pointer"
            >
              <Download className="w-4 h-4" />
              Export Unofficial Working Draft CSV (eTIMS)
            </button>
          </div>
        </div>
      </div>
    </ToolShell>
  );
}
